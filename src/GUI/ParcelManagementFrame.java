    private void refreshTable() {
        DefaultTableModel tableModel = (DefaultTableModel) jTable1.getModel();
        
        tableModel.setRowCount(0);
        for (Parcel p : parcelManager.getAllParcels()) {
            tableModel.addRow(new Object[]{
                p.getTrackingId(), 
                p.getParcelType(), 
                p.getSender(), 
                p.getReceiver(), 
                p.getWeight(), //Double
                p.getStatus(), 
                p.calculatePrice() // String.formatDouble .
            });
        }
    }

