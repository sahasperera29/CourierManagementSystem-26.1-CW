    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        //btn update
        String id = FieldTrackid.getText().trim();
        if (id.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please select or type a Tracking ID first.");
            return;
        }

        String[] options = {"Pending", "In Transit", "Delivered"};
        String newStatus = (String) JOptionPane.showInputDialog(this, "Select New Status:",
            "Update Status", JOptionPane.QUESTION_MESSAGE, null, options, options[0]);

        if (newStatus != null) {
            if (parcelManager.updateStatus(id, newStatus)) {
                refreshTable();
                JOptionPane.showMessageDialog(this, "Status Updated!");
            } else {
                JOptionPane.showMessageDialog(this, "Parcel not found!");
            }
        }
    }//GEN-LAST:event_btnUpdateActionPerformed

