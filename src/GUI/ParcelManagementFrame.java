    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        // btn delete
        String id = FieldTrackid.getText().trim();
        if (id.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please select a parcel to delete.");
            return;
        }

        int confirm = JOptionPane.showConfirmDialog(this, "Are you sure you want to delete Parcel " + id + "?", "Confirm", JOptionPane.YES_NO_OPTION);
        if (confirm == JOptionPane.YES_OPTION) {
            if (parcelManager.deleteParcel(id)) {
                refreshTable();
                clearFields();
                JOptionPane.showMessageDialog(this, "Parcel Deleted!");
            } else {
                JOptionPane.showMessageDialog(this, "Parcel not found!");
            }
        }
    }//GEN-LAST:event_btnDeleteActionPerformed

    private void btnViewActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnViewActionPerformed
        //btn view recipt
        String id = FieldTrackid.getText().trim();
        Parcel p = parcelManager.findByTrackingId(id);

        if (p == null) {
            JOptionPane.showMessageDialog(this, "Please select a valid parcel from the table.");
            return;
        }

        StringBuilder receipt = new StringBuilder();
        receipt.append("=== COURIER RECEIPT ===\n");
        receipt.append("Tracking ID : ").append(p.getTrackingId()).append("\n");
        receipt.append("Type        : ").append(p.getParcelType()).append("\n");
        receipt.append("Sender      : ").append(p.getSender()).append("\n");
        receipt.append("Receiver    : ").append(p.getReceiver()).append("\n");
        receipt.append("Weight      : ").append(p.getWeight()).append(" kg\n");
        receipt.append("Status      : ").append(p.getStatus()).append("\n");
        receipt.append("----------------------------\n");
        receipt.append(String.format("TOTAL PRICE : Rs. %.2f\n", p.calculatePrice()));
        receipt.append("=======================");

        JOptionPane.showMessageDialog(this, receipt.toString(), "Receipt", JOptionPane.INFORMATION_MESSAGE);
    }//GEN-LAST:event_btnViewActionPerformed

