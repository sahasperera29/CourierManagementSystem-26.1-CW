    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        // btn add
        try{
            String id = FieldTrackid.getText().trim();
            String sender = FieldSender.getText().trim();
            String receiver = FieldReceiver.getText().trim();
            String type = jComboBox1.getSelectedItem().toString();

            //check if empty
            if(id.isEmpty() || sender.isEmpty() || receiver.isEmpty() || FieldWeight.getText().trim().isEmpty()){
                JOptionPane.showMessageDialog(this, "Please fill in all required fields!");
                return;
            }

            double weight = Double.parseDouble(FieldWeight.getText().trim());
            Parcel p;

            if (type.equals("Express")){
                double surcharge = FieldSurcharge.getText().trim().isEmpty() ? 0.0 : Double.parseDouble(FieldSurcharge.getText().trim());
                p = new ExpressParcel(id, sender, receiver, weight, "Pending", surcharge);
            }else {
                p = new StandardParcel(id, sender, receiver, weight, "Pending");
            }

            if(parcelManager.addParcel(p)){
                JOptionPane.showMessageDialog(this, "Parcel Added Successfully!");
                refreshTable();
                clearFields();
            } else{
                JOptionPane.showMessageDialog(this, "A Parcel with this Tracking ID already exists!");
            }
        }catch(NumberFormatException e){
            JOptionPane.showMessageDialog(this, "Weight and Surcharge must be valid numbers!", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnAddActionPerformed

